function kwemaLang() {
  const saved = localStorage.getItem('kwema_lang');
  if (saved && KWEMA_I18N[saved]) return saved;
  const nav = (navigator.language || 'sw').slice(0, 2);
  // Only French is honoured from the browser; see the note at the top.
  return nav === 'fr' ? 'fr' : 'sw';
}

function kwemaT(key, lang) {
  const l = lang || kwemaLang();
  return (KWEMA_I18N[l] && KWEMA_I18N[l][key]) || KWEMA_I18N.sw[key] || key;
}

function kwemaApplyI18n(lang) {
  const l = lang || kwemaLang();
  document.documentElement.lang = l;
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const v = kwemaT(el.dataset.i18n, l);
    if (v) el.textContent = v;
  });
  document.querySelectorAll('[data-i18n-ph]').forEach((el) => {
    const v = kwemaT(el.dataset.i18nPh, l);
    if (v) el.placeholder = v;
  });
}

function kwemaSetLang(lang) {
  localStorage.setItem('kwema_lang', lang);
  kwemaApplyI18n(lang);
  document.querySelectorAll('#lang button').forEach((b) => {
    b.classList.toggle('on', b.dataset.lang === lang);
  });
}

/** TZS: no subunit, comma separator, symbol first. */
function kwemaTzs(cents) {
  return 'TSh ' + Math.round(cents / 100).toLocaleString('en-US');
}
